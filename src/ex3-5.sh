#!/bin/bash

# 내부 함수 정의 (5페이지 요구사항: 인자를 받아 ls 옵션으로 실행)
run_ls_func() {
    echo "프로그램을 시작합니다."
    echo "함수 안으로 들어 왔음"
    ls "$@"
    echo "프로그램을 종료합니다."
}

# 1. 실행할 때 인자(-l, -1 등)를 주고 실행한 경우 (5페이지 기능 수행)
if [ "$#" -gt 0 ]; then
    run_ls_func "$@"
    exit 0
fi

# 2. 인자 없이 그냥 실행한 경우 (4페이지 시스템 상태 확인 메뉴 + 함수 테스트 제공)
while true; do
    echo "==============================="
    echo "    Ex3-5 시스템 관리 메뉴"
    echo "==============================="
    echo " 1) 사용자 정보 확인"
    echo " 2) CPU 사용률 확인"
    echo " 3) 메모리 사용량 확인"
    echo " 4) 디스크 사용량 확인"
    echo " 5) ls 함수 실행 테스트 (-l 옵션)"
    echo " 6) 종료"
    echo "==============================="
    echo -n "원하는 메뉴를 선택하세요 [1-6]: "
    read menu

    case $menu in
        1)
            echo "--- [사용자 정보] ---"
            whoami
            w
            ;;
        2)
            echo "--- [CPU 사용률] ---"
            top -b -n 1 | head -n 15
            ;;
        3)
            echo "--- [메모리 사용량] ---"
            free -h
            ;;
        4)
            echo "--- [디스크 사용량] ---"
            df -h
            ;;
        5)
            run_ls_func "-l"
            ;;
        6)
            echo "프로그램을 종료합니다."
            exit 0
            ;;
        *)
            echo "잘못된 입력입니다. 1~6 사이의 숫자를 입력하세요."
            ;;
    esac
    echo ""
done

